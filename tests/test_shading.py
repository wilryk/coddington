def test_fully_occluded_mirror_sees_no_sun():
    target = MirrorGeometry.build(0, 0, 90.0, 45.0, 2500, 1500)
    to_sun = sun_vector(180.0, 10.0)
    occ_centre = target.centre + to_sun * 8000.0
    u = np.cross(np.array([0.0, 0.0, 1.0]), -to_sun)
    u /= np.linalg.norm(u)
    v = np.cross(-to_sun, u)
    occluder = MirrorGeometry(
        centre=occ_centre, normal=-to_sun, u=u, v=v, half_width=20000, half_height=20000
    )
    frac = _fraction_unoccluded(target.sample_points(), to_sun, [occluder])
    assert abs(frac) < 1e-9


