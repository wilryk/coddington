"""Tests for heliostat.geometry.shading.

Three kinds of coverage:

(a) The hand-checkable cases from :func:`heliostat.geometry.shading.self_check`,
    split into individual pytest functions for isolated failure reporting,
    plus one smoke test that runs the whole battery.
(b) Fixture parity: :mod:`tests.fixtures.shading` was generated by the
    private source research code's field + shading modules on the real
    field file.
    ``geometry.csv`` carries enough of the scene (target heliostats and
    every neighbour that fed into their numbers) to rebuild it exactly with
    the PUBLIC module and reproduce ``occlusion.csv`` to 1e-9.
(c) The union-vs-product regression: :func:`occlusion_efficiency`'s union
    must exceed ``eta_shade * eta_block`` on an overlapping-occlusion case,
    and the two must differ measurably (not just by float noise).
"""

