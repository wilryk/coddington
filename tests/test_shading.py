@pytest.fixture(scope="module")
def shading_fixture():
    expected = json.loads((SHADING_ROOT / "expected.json").read_text(encoding="utf-8"))
    occlusion = pd.read_csv(SHADING_ROOT / "occlusion.csv")
    geometry = pd.read_csv(SHADING_ROOT / "geometry.csv")
    return expected, occlusion, geometry


def _rebuild_secondary(expected: dict):
    info = expected["secondary"]
    if info is None:
        return None
    assert info["type"] == "SecondaryCone"
    return SecondaryCone(
        z_tip_mm=info["z_tip_mm"],
        angle_deg=info["angle_deg"],
        aperture_radius_mm=info["aperture_radius_mm"],
    )


@pytest.mark.parametrize(
    "step_key",
    ["20260321_1828", "20260321_0939", "20260321_1235"],
)
def test_shading_fixture_parity(shading_fixture, step_key):
    expected, occlusion, geometry = shading_fixture
    group = geometry[geometry["step_key"] == step_key].reset_index(drop=True)
    assert len(group) == expected["n_geometry_rows"] / 3

    field = HeliostatField(
        x_mm=group["x_mm"].to_numpy(float),
        y_mm=group["y_mm"].to_numpy(float),
        ids=group["heliostat_id"].to_numpy(int),
        mirror_width_mm=expected["mirror_width_mm"],
        mirror_height_mm=expected["mirror_height_mm"],
    )
    neighbours = neighbour_pairs(field, expected["search_radius_mm"])

    rot_az = group["rot_az_deg"].to_numpy(float)
    rot_el = group["rot_el_deg"].to_numpy(float)
    aims = group[["aim_x_mm", "aim_y_mm", "aim_z_mm"]].to_numpy(float)

    geoms, aim_points = build_geometries(
        field, rot_az, rot_el, aims, pedestal_height_mm=expected["pedestal_height_mm"]
    )

    sun_row = next(s for label, s in expected["sun_positions"].items() if s["key"] == step_key)
    secondary = _rebuild_secondary(expected)

    eta_shade, eta_block, eta_secondary = shading_blocking(
        geoms,
        aim_points,
        sun_row["solar_az_deg"],
        sun_row["solar_el_deg"],
        neighbours,
        secondary=secondary,
    )
    eta_union = occlusion_efficiency(
        geoms,
        aim_points,
        sun_row["solar_az_deg"],
        sun_row["solar_el_deg"],
        neighbours,
        secondary=secondary,
    )

    got = pd.DataFrame(
        {
            "heliostat_id": field.ids,
            "eta_shade": eta_shade,
            "eta_block": eta_block,
            "eta_secondary": eta_secondary,
            "eta_union": eta_union,
        }
    ).set_index("heliostat_id")

    want = occlusion[occlusion["step_key"] == step_key].set_index("heliostat_id")
    assert len(want) == 15

    for col in ("eta_shade", "eta_block", "eta_secondary", "eta_union"):
        np.testing.assert_allclose(
            got.loc[want.index, col].to_numpy(),
            want[col].to_numpy(),
            atol=1e-9,
            rtol=0,
            err_msg=f"{col} mismatch at step {step_key}",
        )


