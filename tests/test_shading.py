# (c) Union vs product regression
# ---------------------------------------------------------------------------


def test_union_exceeds_product_under_overlapping_occlusion():
    """One neighbour that shades AND blocks the SAME patch of the target's
    aperture: eta_shade * eta_block treats the two losses as independent and
    removes that overlapping patch twice, understating eta relative to the
    true union.

    The aim point here is placed roughly along the sun direction from the
    target (not a physically focused aim point) purely so the shaded and
    blocked regions coincide by construction, isolating the union-vs-product
    difference from any question of how much the two regions happen to
    overlap in a real, focused scene.
    """
    hw, hh = 2500.0, 1500.0
    target = MirrorGeometry.build(0.0, 0.0, 8.0, 45.0, hw, hh)
    to_sun = sun_vector(90.0, 45.0)
    aim = target.centre + to_sun * 100000.0

    # A single neighbour, up-sun and (because aim ~ to_sun) up-beam too,
    # shifted half a mirror-width sideways so it covers part -- not all --
    # of the aperture, which is what makes eta_shade and eta_block partial
    # (not both driven to 0, where union and product would coincide).
    occ_centre = target.centre + to_sun * 6000.0 + target.u * hw
    occluder = MirrorGeometry(
        centre=occ_centre,
        normal=target.normal,
        u=target.u,
        v=target.v,
        half_width=hw,
        half_height=hh,
    )
    neighbours = [np.array([1]), np.array([])]
    geoms = [target, occluder]
    aims = np.tile(aim, (2, 1))

    eta_shade, eta_block, _ = shading_blocking(geoms, aims, 90.0, 45.0, neighbours)
    eta_union = occlusion_efficiency(geoms, aims, 90.0, 45.0, neighbours)

    # Sanity: this case actually occludes a meaningful, partial share.
    assert 0.1 < eta_shade[0] < 0.9
    assert 0.1 < eta_block[0] < 0.9

    product = eta_shade[0] * eta_block[0]
    assert eta_union[0] > product
    assert eta_union[0] - product > 1e-3
